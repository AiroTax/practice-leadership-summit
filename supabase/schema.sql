-- Practice Leadership Summit: database for the website, the team console and the emails.
-- Paste this whole file into Supabase → SQL Editor → New query → Run. Safe to run again.
-- Only the website's server (with the service key) reads or writes these tables; row level
-- security is on with no public policies, so the public "anon" key can't see anything.

create extension if not exists pgcrypto;

create table if not exists practices (
  id              uuid primary key default gen_random_uuid(),
  number          integer generated by default as identity unique,
  reference       text generated always as ('PLS-' || lpad(number::text, 3, '0')) stored,
  created_at      timestamptz not null default now(),
  name            text not null,
  town            text,
  website         text,
  type            text,
  ticket          text,
  extra           integer,
  people          integer,
  price           integer,
  kasper          boolean not null default false,
  owner_name      text,
  owner_email     text,
  owner_phone     text,
  invoice_email   text,
  members         jsonb not null default '[]',   -- [{name, role, email}]
  heard           text,
  referred_by     text,
  diet            text,
  access          text,
  hotel           text,
  consent_photo   boolean not null default false,
  consent_kasper  boolean not null default false,
  consent_gad     boolean not null default false,
  consent_intros  boolean not null default false,
  terms_at        timestamptz,
  -- team console
  invoice         text not null default 'To send',     -- To send / Sent / Paid
  call            text not null default 'Not booked',  -- Not booked / Booked / Done
  windso          text not null default 'None',        -- None / Eligible / Offered / Claimed
  day30           boolean not null default false,
  notes           text,
  checked_in      jsonb not null default '[false,false,false,false]', -- owner, member 1, 2, 3
  report_key      text unique,
  report_status   text not null default 'Draft',       -- Draft / Ready / Sent
  report_note     text,
  report_sent_at  timestamptz,
  updated_at      timestamptz not null default now()
);

create table if not exists prework (
  id          uuid primary key default gen_random_uuid(),
  number      integer not null references practices(number) on delete cascade,
  created_at  timestamptz not null default now(),
  email       text,
  answered_by text,
  answers     jsonb not null default '{}'
);
create index if not exists prework_number on prework(number, created_at desc);

-- The email journey: one row per email, holding the team's approval and any edits to the text.
create table if not exists journey (
  id          text primary key,
  status      text not null default 'draft',   -- draft / approved / paused
  subject     text,
  body        text,
  vars        jsonb not null default '{}',     -- values for placeholders like {{venue_name}}
  updated_by  text,
  updated_at  timestamptz not null default now()
);

-- Every email the system sends, so nothing goes out twice.
create table if not exists email_log (
  id           bigint generated always as identity primary key,
  created_at   timestamptz not null default now(),
  practice_id  uuid references practices(id) on delete set null,
  email_id     text not null,
  to_addr      text,
  subject      text,
  status       text not null,                  -- sent / failed / skipped
  provider_id  text,
  error        text
);
create unique index if not exists email_log_once on email_log(practice_id, email_id) where status = 'sent' and email_id like 'e%';
create index if not exists email_log_recent on email_log(created_at desc);

alter table practices enable row level security;
alter table prework   enable row level security;
alter table journey   enable row level security;
alter table email_log enable row level security;
